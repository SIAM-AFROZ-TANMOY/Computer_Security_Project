"""#Build Character-Level CNN Model"""

cnn_model = Sequential([

    # Character embedding
    Embedding(
        input_dim=VOCAB_SIZE,
        output_dim=64,
        input_length=MAX_LENGTH
    ),

    # First convolution layer
    Conv1D(
        filters=128,
        kernel_size=5,
        activation="relu",
        padding="same"
    ),

    BatchNormalization(),

    # Second convolution layer
    Conv1D(
        filters=128,
        kernel_size=3,
        activation="relu",
        padding="same"
    ),

    # Convert sequence into fixed-size representation
    GlobalMaxPooling1D(),

    # Fully connected layer
    Dense(
        128,
        activation="relu"
    ),

    Dropout(0.40),

    # Binary classification output
    Dense(
        1,
        activation="sigmoid"
    )
])

